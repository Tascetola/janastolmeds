--changeset adetola:030-01
--comment: JM_DOCTOR_SCHEDULES: weekly sessions per doctor (FR-APT-01)
CREATE TABLE jm_doctor_schedules (
    schedule_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    staff_id             NUMBER NOT NULL,
    day_of_week          NUMBER(1) NOT NULL,
    start_time           VARCHAR2(5 CHAR) NOT NULL,
    end_time             VARCHAR2(5 CHAR) NOT NULL,
    slot_minutes         NUMBER(3) NOT NULL,
    max_patients         NUMBER(3) NOT NULL,
    valid_from           DATE NOT NULL,
    valid_to             DATE,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_doctor_schedules_pk PRIMARY KEY (schedule_id),
    CONSTRAINT jm_doctor_schedules_staff_fk FOREIGN KEY (staff_id) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_doctor_schedules_day_ck CHECK (day_of_week BETWEEN 1 AND 7),
    CONSTRAINT jm_doctor_schedules_start_ck CHECK (REGEXP_LIKE(start_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT jm_doctor_schedules_end_ck CHECK (REGEXP_LIKE(end_time, '^([01][0-9]|2[0-3]):[0-5][0-9]$')),
    CONSTRAINT jm_doctor_schedules_window_ck CHECK (end_time > start_time),
    CONSTRAINT jm_doctor_schedules_slot_ck CHECK (slot_minutes BETWEEN 5 AND 240),
    CONSTRAINT jm_doctor_schedules_max_ck CHECK (max_patients > 0),
    CONSTRAINT jm_doctor_schedules_valid_ck CHECK (valid_to IS NULL OR valid_to >= valid_from)
);
--rollback DROP TABLE jm_doctor_schedules CASCADE CONSTRAINTS PURGE;

--changeset adetola:030-02
--comment: JM_APPOINTMENTS: booked slots and status (FR-APT-02, FR-APT-03, FR-APT-04)
CREATE TABLE jm_appointments (
    appointment_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    appointment_no       VARCHAR2(20 CHAR) NOT NULL,
    patient_id           NUMBER NOT NULL,
    staff_id             NUMBER NOT NULL,
    schedule_id          NUMBER NOT NULL,
    slot_start           DATE NOT NULL,
    slot_end             DATE NOT NULL,
    reason               VARCHAR2(300 CHAR),
    status               VARCHAR2(15 CHAR) DEFAULT 'BOOKED' NOT NULL,
    booked_via           VARCHAR2(10 CHAR) DEFAULT 'DESK' NOT NULL,
    checked_in_at        TIMESTAMP WITH LOCAL TIME ZONE,
    cancelled_at         TIMESTAMP WITH LOCAL TIME ZONE,
    cancel_reason        VARCHAR2(200 CHAR),
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_appointments_pk PRIMARY KEY (appointment_id),
    CONSTRAINT jm_appointments_no_uk UNIQUE (appointment_no),
    CONSTRAINT jm_appointments_patient_fk FOREIGN KEY (patient_id) REFERENCES jm_patients (patient_id),
    CONSTRAINT jm_appointments_staff_fk FOREIGN KEY (staff_id) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_appointments_schedule_fk FOREIGN KEY (schedule_id) REFERENCES jm_doctor_schedules (schedule_id),
    CONSTRAINT jm_appointments_status_ck CHECK (status IN ('BOOKED', 'CHECKED_IN', 'IN_CONSULT', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT jm_appointments_via_ck CHECK (booked_via IN ('DESK', 'MOBILE')),
    CONSTRAINT jm_appointments_slot_ck CHECK (slot_end > slot_start)
);
--rollback DROP TABLE jm_appointments CASCADE CONSTRAINTS PURGE;

--changeset adetola:030-03
--comment: Block double-booking: one active appointment per doctor slot (FR-APT-02)
CREATE UNIQUE INDEX jm_appointments_slot_uk ON jm_appointments (
    CASE WHEN status NOT IN ('CANCELLED','NO_SHOW') THEN staff_id END,
    CASE WHEN status NOT IN ('CANCELLED','NO_SHOW') THEN slot_start END
);
--rollback DROP INDEX jm_appointments_slot_uk;
