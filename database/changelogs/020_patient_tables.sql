CREATE TABLE jm_patients (
    patient_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    mrn                  VARCHAR2(20 CHAR) NOT NULL,
    first_name           VARCHAR2(60 CHAR) NOT NULL,
    middle_name          VARCHAR2(60 CHAR),
    last_name            VARCHAR2(60 CHAR) NOT NULL,
    date_of_birth        DATE NOT NULL,
    gender               VARCHAR2(10 CHAR) NOT NULL,
    blood_group          VARCHAR2(5 CHAR),
    genotype             VARCHAR2(5 CHAR),
    phone                VARCHAR2(20 CHAR) NOT NULL,
    email                VARCHAR2(150 CHAR),
    address              VARCHAR2(300 CHAR),
    state_of_origin      VARCHAR2(50 CHAR),
    nok_name             VARCHAR2(120 CHAR),
    nok_phone            VARCHAR2(20 CHAR),
    nok_relationship     VARCHAR2(30 CHAR),
    hmo_plan_id          NUMBER,
    hmo_member_no        VARCHAR2(30 CHAR),
    photo                BLOB,
    photo_mime           VARCHAR2(50 CHAR),
    status               VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    reg_channel          VARCHAR2(10 CHAR) DEFAULT 'DESK' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_patients_pk PRIMARY KEY (patient_id),
    CONSTRAINT jm_patients_mrn_uk UNIQUE (mrn),
    CONSTRAINT jm_patients_hmo_plan_fk FOREIGN KEY (hmo_plan_id) REFERENCES jm_hmo_plans (hmo_plan_id),
    CONSTRAINT jm_patients_gender_ck CHECK (gender IN ('MALE', 'FEMALE')),
    CONSTRAINT jm_patients_status_ck CHECK (status IN ('PENDING', 'ACTIVE', 'ANONYMISED')),
    CONSTRAINT jm_patients_reg_channel_ck CHECK (reg_channel IN ('DESK', 'MOBILE')),
    CONSTRAINT jm_patients_hmo_member_ck CHECK (hmo_plan_id IS NULL OR hmo_member_no IS NOT NULL)
);
