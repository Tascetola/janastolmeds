--comment: JM_HMO_PLANS: HMOs and plans with coverage share (FR-BIL-03)
CREATE TABLE jm_hmo_plans (
    hmo_plan_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    hmo_name             VARCHAR2(100 CHAR) NOT NULL,
    plan_name            VARCHAR2(100 CHAR) NOT NULL,
    coverage_pct         NUMBER(5,2) NOT NULL,
    claims_email         VARCHAR2(150 CHAR),
    active_flag          VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_hmo_plans_pk PRIMARY KEY (hmo_plan_id),
    CONSTRAINT jm_hmo_plans_uk UNIQUE (hmo_name, plan_name),
    CONSTRAINT jm_hmo_plans_coverage_ck CHECK (coverage_pct BETWEEN 0 AND 100),
    CONSTRAINT jm_hmo_plans_active_flag_ck CHECK (active_flag IN ('Y','N'))
);
