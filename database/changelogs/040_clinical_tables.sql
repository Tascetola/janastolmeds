--changeset adetola:040-02
--comment: JM_VISITS: one outpatient encounter, the hub of the model (FR-CLN-02, FR-CLN-03, FR-CLN-04)
CREATE TABLE jm_visits (
    visit_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    visit_no             VARCHAR2(20 CHAR) NOT NULL,
    patient_id           NUMBER NOT NULL,
    appointment_id       NUMBER,
    doctor_id            NUMBER NOT NULL,
    visit_date           DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    triage_priority      NUMBER(1) DEFAULT 4 NOT NULL,
    chief_complaint      VARCHAR2(500 CHAR),
    history_notes        CLOB,
    exam_notes           CLOB,
    plan_notes           CLOB,
    status               VARCHAR2(15 CHAR) DEFAULT 'OPEN' NOT NULL,
    completed_at         TIMESTAMP WITH LOCAL TIME ZONE,
    locked_at            TIMESTAMP WITH LOCAL TIME ZONE,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_visits_pk PRIMARY KEY (visit_id),
    CONSTRAINT jm_visits_no_uk UNIQUE (visit_no),
    CONSTRAINT jm_visits_appointment_uk UNIQUE (appointment_id),
    CONSTRAINT jm_visits_patient_fk FOREIGN KEY (patient_id) REFERENCES jm_patients (patient_id),
    CONSTRAINT jm_visits_appointment_fk FOREIGN KEY (appointment_id) REFERENCES jm_appointments (appointment_id),
    CONSTRAINT jm_visits_doctor_fk FOREIGN KEY (doctor_id) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_visits_triage_ck CHECK (triage_priority BETWEEN 1 AND 4),
    CONSTRAINT jm_visits_status_ck CHECK (status IN ('OPEN', 'COMPLETED', 'LOCKED')),
    CONSTRAINT jm_visits_completed_ck CHECK (status = 'OPEN' OR completed_at IS NOT NULL)
);
--rollback DROP TABLE jm_visits CASCADE CONSTRAINTS PURGE;

--changeset adetola:040-03
--comment: JM_VITALS: vital signs with plausible ranges and derived BMI (FR-CLN-01)
CREATE TABLE jm_vitals (
    vitals_id            NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    visit_id             NUMBER NOT NULL,
    taken_by             NUMBER NOT NULL,
    taken_at             TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    temperature_c        NUMBER(4,1),
    systolic_bp          NUMBER(3),
    diastolic_bp         NUMBER(3),
    pulse_bpm            NUMBER(3),
    resp_rate            NUMBER(3),
    spo2_pct             NUMBER(3),
    weight_kg            NUMBER(5,1),
    height_cm            NUMBER(5,1),
    bmi                  NUMBER(6,1) GENERATED ALWAYS AS (CASE WHEN height_cm > 0 THEN ROUND(weight_kg / POWER(height_cm / 100, 2), 1) END) VIRTUAL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_vitals_pk PRIMARY KEY (vitals_id),
    CONSTRAINT jm_vitals_visit_fk FOREIGN KEY (visit_id) REFERENCES jm_visits (visit_id),
    CONSTRAINT jm_vitals_taken_by_fk FOREIGN KEY (taken_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_vitals_temp_ck CHECK (temperature_c BETWEEN 30 AND 45),
    CONSTRAINT jm_vitals_systolic_ck CHECK (systolic_bp BETWEEN 50 AND 260),
    CONSTRAINT jm_vitals_diastolic_ck CHECK (diastolic_bp BETWEEN 30 AND 160),
    CONSTRAINT jm_vitals_pulse_ck CHECK (pulse_bpm BETWEEN 20 AND 250),
    CONSTRAINT jm_vitals_resp_ck CHECK (resp_rate BETWEEN 5 AND 80),
    CONSTRAINT jm_vitals_spo2_ck CHECK (spo2_pct BETWEEN 50 AND 100),
    CONSTRAINT jm_vitals_weight_ck CHECK (weight_kg BETWEEN 0.5 AND 400),
    CONSTRAINT jm_vitals_height_ck CHECK (height_cm BETWEEN 30 AND 250)
);
--rollback DROP TABLE jm_vitals CASCADE CONSTRAINTS PURGE;

