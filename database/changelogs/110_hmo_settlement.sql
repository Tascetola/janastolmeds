--changeset adetola:110-trg-hmo_claims endDelimiter:/ runOnChange:true stripComments:false
--comment: Standard audit columns and optimistic-lock version for JM_HMO_CLAIMS
CREATE OR REPLACE TRIGGER jm_hmo_claims_biu
BEFORE INSERT OR UPDATE ON jm_hmo_claims
FOR EACH ROW
BEGIN
    IF INSERTING THEN
        :new.created_by  := jm_current_user;
        :new.created_on  := SYSTIMESTAMP;
        :new.row_version := 1;
    ELSE
        :new.created_by  := :old.created_by;
        :new.created_on  := :old.created_on;
        :new.updated_by  := jm_current_user;
        :new.updated_on  := SYSTIMESTAMP;
        :new.row_version := :old.row_version + 1;
    END IF;
END;
/
--rollback DROP TRIGGER jm_hmo_claims_biu;

