-- DEF-009 (decided 29 Oct 2026): HMO settlement is tracked separately from patient payments.
-- JM_PAYMENTS holds money from the patient only; the HMO share of an invoice is claimed and
-- remitted through JM_HMO_CLAIMS, and JM_INVOICES.HMO_AMOUNT_PAID totals what the HMO has paid.

--changeset adetola:110-01
--comment: JM_HMO_CLAIMS: claim of an invoice's HMO share, approval and remittance (FR-BIL-03, FR-BIL-04; DEF-009)
CREATE TABLE jm_hmo_claims (
    claim_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    claim_no             VARCHAR2(20 CHAR) NOT NULL,
    invoice_id           NUMBER NOT NULL,
    hmo_plan_id          NUMBER NOT NULL,
    claim_amount         NUMBER(12,2) NOT NULL,
    approved_amount      NUMBER(12,2),
    paid_amount          NUMBER(12,2) DEFAULT 0 NOT NULL,
    status               VARCHAR2(12 CHAR) DEFAULT 'DRAFT' NOT NULL,
    submitted_at         TIMESTAMP WITH LOCAL TIME ZONE,
    decided_at           TIMESTAMP WITH LOCAL TIME ZONE,
    paid_at              TIMESTAMP WITH LOCAL TIME ZONE,
    remittance_ref       VARCHAR2(60 CHAR),
    rejection_reason     VARCHAR2(300 CHAR),
    record_status        VARCHAR2(10 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    deleted_on           TIMESTAMP WITH LOCAL TIME ZONE,
    deleted_by           VARCHAR2(100 CHAR),
    delete_reason        VARCHAR2(300 CHAR),
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_hmo_claims_pk PRIMARY KEY (claim_id),
    CONSTRAINT jm_hmo_claims_no_uk UNIQUE (claim_no),
    CONSTRAINT jm_hmo_claims_invoice_fk FOREIGN KEY (invoice_id) REFERENCES jm_invoices (invoice_id),
    CONSTRAINT jm_hmo_claims_hmo_plan_fk FOREIGN KEY (hmo_plan_id) REFERENCES jm_hmo_plans (hmo_plan_id),
    CONSTRAINT jm_hmo_claims_amounts_ck CHECK (claim_amount > 0 AND paid_amount >= 0
                                               AND (approved_amount IS NULL OR approved_amount BETWEEN 0 AND claim_amount)),
    CONSTRAINT jm_hmo_claims_paid_ck CHECK (paid_amount <= NVL(approved_amount, 0)),
    CONSTRAINT jm_hmo_claims_status_ck CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'PART_PAID', 'PAID', 'REJECTED')),
    CONSTRAINT jm_hmo_claims_submitted_ck CHECK (status = 'DRAFT' OR submitted_at IS NOT NULL),
    CONSTRAINT jm_hmo_claims_decided_ck CHECK (status IN ('DRAFT', 'SUBMITTED') OR decided_at IS NOT NULL),
    CONSTRAINT jm_hmo_claims_rejected_ck CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL),
    CONSTRAINT jm_hmo_claims_record_status_ck CHECK (record_status IN ('ACTIVE', 'DELETED')),
    CONSTRAINT jm_hmo_claims_deleted_ck CHECK (
        (record_status = 'DELETED' AND deleted_on IS NOT NULL AND deleted_by IS NOT NULL AND delete_reason IS NOT NULL)
        OR (record_status <> 'DELETED' AND deleted_on IS NULL AND deleted_by IS NULL AND delete_reason IS NULL))
);
--rollback DROP TABLE jm_hmo_claims CASCADE CONSTRAINTS PURGE;

