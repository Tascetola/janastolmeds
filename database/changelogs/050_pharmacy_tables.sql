    CONSTRAINT jm_dispenses_pk PRIMARY KEY (dispense_id),
    CONSTRAINT jm_dispenses_prescription_fk FOREIGN KEY (prescription_id) REFERENCES jm_prescriptions (prescription_id),
    CONSTRAINT jm_dispenses_batch_fk FOREIGN KEY (batch_id) REFERENCES jm_drug_batches (batch_id),
    CONSTRAINT jm_dispenses_by_fk FOREIGN KEY (dispensed_by) REFERENCES jm_staff (staff_id),
