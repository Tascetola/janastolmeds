--changeset adetola:050-01
--comment: JM_DRUGS: drug formulary with price and reorder level (FR-PHM-01, FR-PHM-04)
CREATE TABLE jm_drugs (
    drug_id              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    drug_code            VARCHAR2(20 CHAR) NOT NULL,
    generic_name         VARCHAR2(150 CHAR) NOT NULL,
    brand_name           VARCHAR2(150 CHAR),
    strength             VARCHAR2(50 CHAR),
    dosage_form          VARCHAR2(30 CHAR) NOT NULL,
    unit_of_issue        VARCHAR2(20 CHAR) NOT NULL,
    unit_price           NUMBER(12,2) NOT NULL,
    reorder_level        NUMBER(8) DEFAULT 0 NOT NULL,
    nafdac_no            VARCHAR2(30 CHAR),
    active_flag          VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_drugs_pk PRIMARY KEY (drug_id),
    CONSTRAINT jm_drugs_code_uk UNIQUE (drug_code),
    CONSTRAINT jm_drugs_price_ck CHECK (unit_price >= 0),
    CONSTRAINT jm_drugs_reorder_ck CHECK (reorder_level >= 0),
    CONSTRAINT jm_drugs_active_flag_ck CHECK (active_flag IN ('Y','N'))
);
--rollback DROP TABLE jm_drugs CASCADE CONSTRAINTS PURGE;

--changeset adetola:050-02
--comment: JM_DRUG_BATCHES: stock per batch with expiry (FR-PHM-03, FR-PHM-04)
CREATE TABLE jm_drug_batches (
    batch_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    drug_id              NUMBER NOT NULL,
    batch_no             VARCHAR2(30 CHAR) NOT NULL,
    expiry_date          DATE NOT NULL,
    qty_received         NUMBER(10) NOT NULL,
    qty_on_hand          NUMBER(10) NOT NULL,
    cost_price           NUMBER(12,2),
    received_on          DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    supplier             VARCHAR2(150 CHAR),
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_drug_batches_pk PRIMARY KEY (batch_id),
    CONSTRAINT jm_drug_batches_uk UNIQUE (drug_id, batch_no),
    CONSTRAINT jm_drug_batches_drug_fk FOREIGN KEY (drug_id) REFERENCES jm_drugs (drug_id),
    CONSTRAINT jm_drug_batches_received_ck CHECK (qty_received > 0),
    CONSTRAINT jm_drug_batches_on_hand_ck CHECK (qty_on_hand >= 0)
);
--rollback DROP TABLE jm_drug_batches CASCADE CONSTRAINTS PURGE;

--changeset adetola:050-03
--comment: JM_PRESCRIPTIONS: one prescribed drug line per visit (FR-PHM-01, FR-PHM-02)
CREATE TABLE jm_prescriptions (
    prescription_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    visit_id             NUMBER NOT NULL,
    drug_id              NUMBER NOT NULL,
    prescribed_by        NUMBER NOT NULL,
    dose                 VARCHAR2(50 CHAR) NOT NULL,
    frequency            VARCHAR2(30 CHAR) NOT NULL,
    duration_days        NUMBER(4) NOT NULL,
    qty_prescribed       NUMBER(8) NOT NULL,
    qty_dispensed        NUMBER(8) DEFAULT 0 NOT NULL,
    instructions         VARCHAR2(300 CHAR),
    allergy_override     VARCHAR2(1) DEFAULT 'N' NOT NULL,
    override_reason      VARCHAR2(300 CHAR),
    status               VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_prescriptions_pk PRIMARY KEY (prescription_id),
    CONSTRAINT jm_prescriptions_visit_fk FOREIGN KEY (visit_id) REFERENCES jm_visits (visit_id),
    CONSTRAINT jm_prescriptions_drug_fk FOREIGN KEY (drug_id) REFERENCES jm_drugs (drug_id),
    CONSTRAINT jm_prescriptions_prescriber_fk FOREIGN KEY (prescribed_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_prescriptions_qty_ck CHECK (qty_prescribed > 0 AND qty_dispensed BETWEEN 0 AND qty_prescribed),
    CONSTRAINT jm_prescriptions_duration_ck CHECK (duration_days > 0),
    CONSTRAINT jm_prescriptions_allergy_override_ck CHECK (allergy_override IN ('Y','N')),
    CONSTRAINT jm_prescriptions_override_ck CHECK (allergy_override = 'N' OR override_reason IS NOT NULL),
    CONSTRAINT jm_prescriptions_status_ck CHECK (status IN ('PENDING', 'PARTIAL', 'DISPENSED', 'CANCELLED'))
);
--rollback DROP TABLE jm_prescriptions CASCADE CONSTRAINTS PURGE;

