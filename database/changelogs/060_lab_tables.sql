--comment: JM_LAB_TESTS: lab test catalogue with reference ranges (FR-LAB-01)
CREATE TABLE jm_lab_tests (
    lab_test_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    test_code            VARCHAR2(20 CHAR) NOT NULL,
    test_name            VARCHAR2(150 CHAR) NOT NULL,
    sample_type          VARCHAR2(30 CHAR) NOT NULL,
    result_type          VARCHAR2(10 CHAR) DEFAULT 'NUMERIC' NOT NULL,
    unit                 VARCHAR2(20 CHAR),
    ref_low              NUMBER,
    ref_high             NUMBER,
    price                NUMBER(12,2) NOT NULL,
    active_flag          VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_lab_tests_pk PRIMARY KEY (lab_test_id),
    CONSTRAINT jm_lab_tests_code_uk UNIQUE (test_code),
    CONSTRAINT jm_lab_tests_result_type_ck CHECK (result_type IN ('NUMERIC', 'TEXT')),
    CONSTRAINT jm_lab_tests_range_ck CHECK (ref_low IS NULL OR ref_high IS NULL OR ref_high >= ref_low),
    CONSTRAINT jm_lab_tests_price_ck CHECK (price >= 0),
    CONSTRAINT jm_lab_tests_active_flag_ck CHECK (active_flag IN ('Y','N'))
);
--rollback DROP TABLE jm_lab_tests CASCADE CONSTRAINTS PURGE;

