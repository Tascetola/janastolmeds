--comment: JM_LAB_ORDERS: tests ordered at a visit and their workflow (FR-LAB-01, FR-LAB-02)
CREATE TABLE jm_lab_orders (
    lab_order_id         NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    order_no             VARCHAR2(20 CHAR) NOT NULL,
    visit_id             NUMBER NOT NULL,
    lab_test_id          NUMBER NOT NULL,
    ordered_by           NUMBER NOT NULL,
    ordered_at           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    urgency              VARCHAR2(10 CHAR) DEFAULT 'ROUTINE' NOT NULL,
    clinical_notes       VARCHAR2(300 CHAR),
    sample_collected_at  TIMESTAMP WITH LOCAL TIME ZONE,
    collected_by         NUMBER,
    status               VARCHAR2(12 CHAR) DEFAULT 'ORDERED' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_lab_orders_pk PRIMARY KEY (lab_order_id),
    CONSTRAINT jm_lab_orders_no_uk UNIQUE (order_no),
    CONSTRAINT jm_lab_orders_visit_fk FOREIGN KEY (visit_id) REFERENCES jm_visits (visit_id),
    CONSTRAINT jm_lab_orders_test_fk FOREIGN KEY (lab_test_id) REFERENCES jm_lab_tests (lab_test_id),
    CONSTRAINT jm_lab_orders_ordered_by_fk FOREIGN KEY (ordered_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_lab_orders_collected_by_fk FOREIGN KEY (collected_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_lab_orders_urgency_ck CHECK (urgency IN ('ROUTINE', 'URGENT')),
    CONSTRAINT jm_lab_orders_status_ck CHECK (status IN ('ORDERED', 'COLLECTED', 'RESULTED', 'RELEASED', 'CANCELLED'))
);
--rollback DROP TABLE jm_lab_orders CASCADE CONSTRAINTS PURGE;

