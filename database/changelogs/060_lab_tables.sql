--comment: JM_LAB_RESULTS: results with two-person verification (FR-LAB-02, FR-LAB-03, FR-LAB-04)
CREATE TABLE jm_lab_results (
    lab_result_id        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    lab_order_id         NUMBER NOT NULL,
    result_numeric       NUMBER,
    result_text          VARCHAR2(1000 CHAR),
    abnormal_flag        VARCHAR2(1) DEFAULT 'N' NOT NULL,
    entered_by           NUMBER NOT NULL,
    entered_at           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    verified_by          NUMBER,
    verified_at          TIMESTAMP WITH LOCAL TIME ZONE,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_lab_results_pk PRIMARY KEY (lab_result_id),
    CONSTRAINT jm_lab_results_order_uk UNIQUE (lab_order_id),
    CONSTRAINT jm_lab_results_order_fk FOREIGN KEY (lab_order_id) REFERENCES jm_lab_orders (lab_order_id),
    CONSTRAINT jm_lab_results_entered_by_fk FOREIGN KEY (entered_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_lab_results_verified_by_fk FOREIGN KEY (verified_by) REFERENCES jm_staff (staff_id),
    CONSTRAINT jm_lab_results_abnormal_ck CHECK (abnormal_flag IN ('L', 'N', 'H')),
    CONSTRAINT jm_lab_results_value_ck CHECK (result_numeric IS NOT NULL OR result_text IS NOT NULL),
    CONSTRAINT jm_lab_results_verifier_ck CHECK (verified_by IS NULL OR verified_by <> entered_by),
    CONSTRAINT jm_lab_results_verified_ck CHECK ((verified_by IS NULL AND verified_at IS NULL) OR (verified_by IS NOT NULL AND verified_at IS NOT NULL))
);
--rollback DROP TABLE jm_lab_results CASCADE CONSTRAINTS PURGE;
