--comment: JM_SERVICES: price list for chargeable services (FR-BIL-01)
CREATE TABLE jm_services (
    service_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    service_code         VARCHAR2(20 CHAR) NOT NULL,
    service_name         VARCHAR2(150 CHAR) NOT NULL,
    department_id        NUMBER,
    price                NUMBER(12,2) NOT NULL,
    active_flag          VARCHAR2(1) DEFAULT 'Y' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_services_pk PRIMARY KEY (service_id),
    CONSTRAINT jm_services_code_uk UNIQUE (service_code),
    CONSTRAINT jm_services_department_fk FOREIGN KEY (department_id) REFERENCES jm_departments (department_id),
    CONSTRAINT jm_services_price_ck CHECK (price >= 0),
    CONSTRAINT jm_services_active_flag_ck CHECK (active_flag IN ('Y','N'))
);
