--comment: JM_INVOICE_LINES: charges traced to their source; each source billed once (FR-BIL-01)
CREATE TABLE jm_invoice_lines (
    invoice_line_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_id           NUMBER NOT NULL,
    source_type          VARCHAR2(12 CHAR) NOT NULL,
    source_id            NUMBER NOT NULL,
    description          VARCHAR2(200 CHAR) NOT NULL,
    qty                  NUMBER(8) DEFAULT 1 NOT NULL,
    unit_price           NUMBER(12,2) NOT NULL,
    line_amount          NUMBER(14,2) GENERATED ALWAYS AS (qty * unit_price) VIRTUAL,
    hmo_covered          VARCHAR2(1) DEFAULT 'N' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_invoice_lines_pk PRIMARY KEY (invoice_line_id),
    CONSTRAINT jm_invoice_lines_source_uk UNIQUE (source_type, source_id),
    CONSTRAINT jm_invoice_lines_invoice_fk FOREIGN KEY (invoice_id) REFERENCES jm_invoices (invoice_id),
    CONSTRAINT jm_invoice_lines_source_type_ck CHECK (source_type IN ('SERVICE', 'LAB', 'DRUG')),
    CONSTRAINT jm_invoice_lines_qty_ck CHECK (qty > 0),
    CONSTRAINT jm_invoice_lines_price_ck CHECK (unit_price >= 0),
    CONSTRAINT jm_invoice_lines_hmo_covered_ck CHECK (hmo_covered IN ('Y','N'))
);
--rollback DROP TABLE jm_invoice_lines CASCADE CONSTRAINTS PURGE;

