--comment: JM_INVOICES: one invoice per visit with HMO and patient portions (FR-BIL-01, FR-BIL-03, FR-BIL-04)
CREATE TABLE jm_invoices (
    invoice_id           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    invoice_no           VARCHAR2(20 CHAR) NOT NULL,
    visit_id             NUMBER NOT NULL,
    patient_id           NUMBER NOT NULL,
    hmo_plan_id          NUMBER,
    invoice_date         DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    total_amount         NUMBER(12,2) DEFAULT 0 NOT NULL,
    hmo_amount           NUMBER(12,2) DEFAULT 0 NOT NULL,
    patient_amount       NUMBER(12,2) DEFAULT 0 NOT NULL,
    amount_paid          NUMBER(12,2) DEFAULT 0 NOT NULL,
    status               VARCHAR2(12 CHAR) DEFAULT 'OPEN' NOT NULL,
    created_by           VARCHAR2(100 CHAR) NOT NULL,
    created_on           TIMESTAMP WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by           VARCHAR2(100 CHAR),
    updated_on           TIMESTAMP WITH LOCAL TIME ZONE,
    row_version          NUMBER DEFAULT 1 NOT NULL,
    CONSTRAINT jm_invoices_pk PRIMARY KEY (invoice_id),
    CONSTRAINT jm_invoices_no_uk UNIQUE (invoice_no),
    CONSTRAINT jm_invoices_visit_uk UNIQUE (visit_id),
    CONSTRAINT jm_invoices_visit_fk FOREIGN KEY (visit_id) REFERENCES jm_visits (visit_id),
    CONSTRAINT jm_invoices_patient_fk FOREIGN KEY (patient_id) REFERENCES jm_patients (patient_id),
    CONSTRAINT jm_invoices_hmo_plan_fk FOREIGN KEY (hmo_plan_id) REFERENCES jm_hmo_plans (hmo_plan_id),
    CONSTRAINT jm_invoices_amounts_ck CHECK (total_amount >= 0 AND hmo_amount >= 0 AND patient_amount >= 0 AND amount_paid >= 0),
    CONSTRAINT jm_invoices_split_ck CHECK (hmo_amount + patient_amount = total_amount),
    CONSTRAINT jm_invoices_paid_ck CHECK (amount_paid <= patient_amount),
    CONSTRAINT jm_invoices_status_ck CHECK (status IN ('OPEN', 'PART_PAID', 'PAID', 'VOID'))
);
--rollback DROP TABLE jm_invoices CASCADE CONSTRAINTS PURGE;

